"""X2 slice 2 verifier-side tests: the offline transparency-log checks.

The log itself is an operator surface (raucle-cloud); these tests pin
the OSS verify path that must accept its proofs with no trust in the
operator: recompute every entry hash from the proof alone, check the
chain linkage, and hold the operator's Ed25519 signature to the head.

Round-trips come in two shapes: proofs crafted here from the spec, and
the committed fixture generated by the cloud implementation (the
cross-repo dogfood: the OSS verifier must accept the log's real
proofs, and a doctored copy must refuse with a named status).
"""

from __future__ import annotations

import hashlib
import json
import time
from pathlib import Path

from raucle.provenance import _b64url_encode, _canonical_json
from raucle.transparency import (
    LOG_GENESIS_PREV_HASH,
    STATUS_LOG_BAD_SIGNATURE,
    STATUS_LOG_CHAIN_BROKEN,
    STATUS_LOG_CONSISTENT,
    STATUS_LOG_HEAD_MISMATCH,
    STATUS_LOG_INCLUDED,
    STATUS_LOG_MALFORMED,
    compute_log_entry_hash,
    verify_log_consistency,
    verify_log_inclusion,
)

ORG = "verifyco"
FIXTURE = Path(__file__).parent / "fixtures" / "transparency-log" / "cloud-roundtrip.json"


# ---------------------------------------------------------------------------
# A local log + checkpoint signer built from the spec alone
# ---------------------------------------------------------------------------


def _entry(org, sequence, prev_hash, receipt_digest, registered_at, payload_digest=None):
    entry = {
        "org": org,
        "sequence": sequence,
        "prev_hash": prev_hash,
        "receipt_digest": receipt_digest,
        "payload_digest": payload_digest,
        "registered_at": registered_at,
        "entry_hash": "",
    }
    entry["entry_hash"] = compute_log_entry_hash(entry)
    return entry


def _digest(seed: str) -> str:
    return "sha256:" + hashlib.sha256(seed.encode("utf-8")).hexdigest()


def _signer():
    from cryptography.hazmat.primitives import serialization
    from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

    private = Ed25519PrivateKey.generate()
    pem = (
        private.public_key()
        .public_bytes(
            encoding=serialization.Encoding.PEM,
            format=serialization.PublicFormat.SubjectPublicKeyInfo,
        )
        .decode("ascii")
    )
    return private, pem


def _checkpoint(private, *, org, size, head_hash, iat=None, typ="transparency-epoch/v1"):
    """One epoch checkpoint in the exact wire format the log service
    emits: EdDSA JWS, kid, typ transparency-epoch/v1."""
    header = {
        "alg": "EdDSA",
        "typ": typ,
        "kid": "raucle-portal-test",
        "crit": ["raucle/v1"],
        "raucle/v1": "transparency",
    }
    payload = {
        "iss": "raucle-portal",
        "org": org,
        "epoch": size,
        "size": size,
        "head_hash": head_hash,
        "iat": int(time.time() if iat is None else iat),
        "nonce": "0" * 32,
    }
    signing_input = (
        _b64url_encode(_canonical_json(header)) + "." + _b64url_encode(_canonical_json(payload))
    ).encode("ascii")
    signature = private.sign(signing_input)
    return signing_input.decode("ascii") + "." + _b64url_encode(signature)


def _build_log(private, org=ORG, count=3):
    entries = []
    prev = LOG_GENESIS_PREV_HASH
    for i in range(1, count + 1):
        entry = _entry(
            org,
            i,
            prev,
            _digest(f"seed-{i}"),
            registered_at=1_700_000_000 + i,
        )
        entries.append(entry)
        prev = entry["entry_hash"]
    return entries


def _inclusion_proof(private, entries, *, target=1):
    head = entries[-1]
    return {
        "org": head["org"],
        "sequence": entries[target - 1]["sequence"],
        "entries": entries[target - 1 :],
        "size": head["sequence"],
        "head_hash": head["entry_hash"],
        "checkpoint_jws": _checkpoint(
            private,
            org=head["org"],
            size=head["sequence"],
            head_hash=head["entry_hash"],
        ),
    }


def _consistency_proof(private, entries, *, from_size=1):
    to_head = entries[-1]
    from_head = entries[from_size - 1]
    return {
        "org": from_head["org"],
        "from_size": from_size,
        "to_size": to_head["sequence"],
        "entries": entries[from_size:],
        "from_checkpoint_jws": _checkpoint(
            private,
            org=from_head["org"],
            size=from_head["sequence"],
            head_hash=from_head["entry_hash"],
        ),
        "to_checkpoint_jws": _checkpoint(
            private,
            org=to_head["org"],
            size=to_head["sequence"],
            head_hash=to_head["entry_hash"],
        ),
    }


# ---------------------------------------------------------------------------
# Inclusion: the round trip and the named refusals
# ---------------------------------------------------------------------------


def test_inclusion_round_trip():
    private, pem = _signer()
    entries = _build_log(private)
    proof = _inclusion_proof(private, entries, target=1)
    result = verify_log_inclusion(proof, operator_public_key_pem=pem)
    assert result.status == STATUS_LOG_INCLUDED, result.reasons
    assert result.size == 3
    assert result.head_hash == entries[-1]["entry_hash"]


def test_inclusion_mid_chain_target_round_trip():
    private, pem = _signer()
    entries = _build_log(private)
    proof = _inclusion_proof(private, entries, target=2)
    result = verify_log_inclusion(
        proof, operator_public_key_pem=pem, expect_digest=_digest("seed-2")
    )
    assert result.status == STATUS_LOG_INCLUDED, result.reasons


def test_expected_digest_binding_is_checked():
    private, pem = _signer()
    entries = _build_log(private)
    proof = _inclusion_proof(private, entries, target=1)
    result = verify_log_inclusion(
        proof, operator_public_key_pem=pem, expect_digest=_digest("seed-2")
    )
    assert result.status == STATUS_LOG_HEAD_MISMATCH
    assert any("different digest" in r for r in result.reasons)


def test_doctored_entry_is_a_named_refusal():
    private, pem = _signer()
    entries = _build_log(private)
    proof = _inclusion_proof(private, entries, target=1)
    proof["entries"][1]["receipt_digest"] = _digest("rewritten-history")
    result = verify_log_inclusion(proof, operator_public_key_pem=pem)
    assert result.status == STATUS_LOG_CHAIN_BROKEN
    assert any("does not bind" in r for r in result.reasons)


def test_relinked_segment_is_a_named_refusal():
    private, pem = _signer()
    entries = _build_log(private)
    proof = _inclusion_proof(private, entries, target=2)
    proof["entries"][1]["prev_hash"] = LOG_GENESIS_PREV_HASH
    result = verify_log_inclusion(proof, operator_public_key_pem=pem)
    assert result.status == STATUS_LOG_CHAIN_BROKEN
    assert any("does not link" in r for r in result.reasons)


def test_genesis_entry_must_name_genesis():
    private, pem = _signer()
    entries = _build_log(private)
    entries[0]["prev_hash"] = _digest("not-genesis")
    entries[0]["entry_hash"] = compute_log_entry_hash(entries[0])
    proof = _inclusion_proof(private, entries, target=1)
    result = verify_log_inclusion(proof, operator_public_key_pem=pem)
    assert result.status == STATUS_LOG_CHAIN_BROKEN


def test_wrong_signing_key_is_a_named_refusal():
    private, _ = _signer()
    other, other_pem = _signer()
    entries = _build_log(private)
    proof = _inclusion_proof(private, entries, target=1)
    result = verify_log_inclusion(proof, operator_public_key_pem=other_pem)
    assert result.status == STATUS_LOG_BAD_SIGNATURE


def test_wrong_checkpoint_typ_is_a_named_refusal():
    private, pem = _signer()
    entries = _build_log(private)
    head = entries[-1]
    proof = _inclusion_proof(private, entries, target=1)
    proof["checkpoint_jws"] = _checkpoint(
        private,
        org=head["org"],
        size=head["sequence"],
        head_hash=head["entry_hash"],
        typ="provenance-receipt/v1",
    )
    result = verify_log_inclusion(proof, operator_public_key_pem=pem)
    assert result.status == STATUS_LOG_BAD_SIGNATURE


def test_head_not_reached_is_a_named_refusal():
    private, pem = _signer()
    entries = _build_log(private)
    proof = _inclusion_proof(private, entries, target=1)
    # A checkpoint over a DIFFERENT head than the segment reaches.
    proof["checkpoint_jws"] = _checkpoint(
        private,
        org=ORG,
        size=3,
        head_hash=_digest("a-head-that-is-not"),
    )
    result = verify_log_inclusion(proof, operator_public_key_pem=pem)
    assert result.status == STATUS_LOG_HEAD_MISMATCH


def test_malformed_proofs_refuse_with_the_named_status():
    private, pem = _signer()
    entries = _build_log(private)
    proof = _inclusion_proof(private, entries, target=1)

    empty = {**proof, "entries": []}
    assert verify_log_inclusion(empty, operator_public_key_pem=pem).status == (STATUS_LOG_MALFORMED)

    missing = {k: v for k, v in proof.items() if k != "checkpoint_jws"}
    assert verify_log_inclusion(missing, operator_public_key_pem=pem).status == STATUS_LOG_MALFORMED

    non_contiguous = {**proof, "entries": [proof["entries"][0], *proof["entries"][2:]]}
    assert (
        verify_log_inclusion(non_contiguous, operator_public_key_pem=pem).status
        == STATUS_LOG_CHAIN_BROKEN
    )

    truncated = {**proof, "entries": proof["entries"][:2]}
    assert (
        verify_log_inclusion(truncated, operator_public_key_pem=pem).status
        == STATUS_LOG_HEAD_MISMATCH
    )


def test_org_binding_is_checked():
    private, pem = _signer()
    entries = _build_log(private, org=ORG)
    proof = _inclusion_proof(private, entries, target=1)
    proof["org"] = "otherco"
    result = verify_log_inclusion(proof, operator_public_key_pem=pem, org="verifyco")
    assert result.status == STATUS_LOG_HEAD_MISMATCH


