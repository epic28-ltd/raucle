def _load_fixture() -> dict:
    assert FIXTURE.is_file(), f"missing committed fixture: {FIXTURE}"
    return json.loads(FIXTURE.read_text(encoding="utf-8"))


def test_cloud_fixture_inclusion_proof_verifies():
    fixture = _load_fixture()
    result = verify_log_inclusion(
        fixture["inclusion_proof"],
        operator_public_key_pem=fixture["operator_public_key_pem"],
        org=fixture["org"],
    )
    assert result.status == STATUS_LOG_INCLUDED, result.reasons
    assert result.size == 3
    assert result.head_hash == fixture["latest"]["head_hash"]


def test_cloud_fixture_expected_digest_binding():
    fixture = _load_fixture()
    result = verify_log_inclusion(
        fixture["inclusion_proof"],
        operator_public_key_pem=fixture["operator_public_key_pem"],
        org=fixture["org"],
        expect_digest=fixture["registered_digests"][0],
    )
    assert result.status == STATUS_LOG_INCLUDED, result.reasons


def test_cloud_fixture_consistency_proof_verifies():
    fixture = _load_fixture()
    result = verify_log_consistency(
        fixture["consistency_proof"],
        operator_public_key_pem=fixture["operator_public_key_pem"],
        org=fixture["org"],
    )
    assert result.status == STATUS_LOG_CONSISTENT, result.reasons


def test_cloud_fixture_doctored_copy_refuses():
    fixture = _load_fixture()
    doctored = json.loads(json.dumps(fixture["inclusion_proof"]))
    doctored["entries"][0]["receipt_digest"] = _digest("doctored")
    result = verify_log_inclusion(
        doctored, operator_public_key_pem=fixture["operator_public_key_pem"]
    )
    assert result.status == STATUS_LOG_CHAIN_BROKEN


def test_cloud_fixture_wrong_key_refuses():
    fixture = _load_fixture()
    _, other_pem = _signer()
    result = verify_log_inclusion(fixture["inclusion_proof"], operator_public_key_pem=other_pem)
    assert result.status == STATUS_LOG_BAD_SIGNATURE


def test_genesis_prev_hash_is_the_documented_constant():
    # The chain a third party recomputes starts from a named value, so
    # the constant is part of the contract, not an implementation detail.
    assert LOG_GENESIS_PREV_HASH == "sha256:" + "0" * 64


def test_entry_hash_is_deterministic_over_canonical_bytes():
    private, _ = _signer()
    entries = _build_log(private, count=1)
    first = entries[0]
    again = _entry(
        first["org"],
        1,
        LOG_GENESIS_PREV_HASH,
        first["receipt_digest"],
        first["registered_at"],
    )
    assert again["entry_hash"] == first["entry_hash"]


