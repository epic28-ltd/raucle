def test_malformed_entry_shapes_refuse_cleanly():
    private, pem = _signer()
    entries = _build_log(private)
    proof = _inclusion_proof(private, entries, target=1)

    no_hash = [{k: v for k, v in proof["entries"][0].items() if k != "entry_hash"}]
    doctored = {**proof, "entries": [*no_hash, *proof["entries"][1:]]}
    result = verify_log_inclusion(doctored, operator_public_key_pem=pem)
    assert result.status == STATUS_LOG_MALFORMED

    bad_digest = [dict(proof["entries"][0])]
    bad_digest[0]["receipt_digest"] = "not-a-digest"
    doctored2 = {**proof, "entries": [*bad_digest, *proof["entries"][1:]]}
    result2 = verify_log_inclusion(doctored2, operator_public_key_pem=pem)
    assert result2.status == STATUS_LOG_MALFORMED
