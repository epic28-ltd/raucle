# Consistency: the round trip and the rewrite refusals
# ---------------------------------------------------------------------------


def test_consistency_round_trip():
    private, pem = _signer()
    entries = _build_log(private)
    proof = _consistency_proof(private, entries, from_size=1)
    result = verify_log_consistency(proof, operator_public_key_pem=pem)
    assert result.status == STATUS_LOG_CONSISTENT, result.reasons
    assert result.size == 3


def test_consistency_detects_a_rewritten_old_head():
    private, pem = _signer()
    entries = _build_log(private)
    proof = _consistency_proof(private, entries, from_size=1)
    # An operator rewriting history: the segment claims to grow from
    # a head that is not the one the old checkpoint signed.
    doctored = [dict(e) for e in proof["entries"]]
    doctored[0]["prev_hash"] = _digest("rewritten-old-head")
    proof = {**proof, "entries": doctored}
    result = verify_log_consistency(proof, operator_public_key_pem=pem)
    assert result.status == STATUS_LOG_CHAIN_BROKEN


def test_consistency_detects_a_bad_from_checkpoint():
    private, pem = _signer()
    entries = _build_log(private)
    proof = _consistency_proof(private, entries, from_size=1)
    proof["from_checkpoint_jws"] = _checkpoint(
        private,
        org=ORG,
        size=1,
        head_hash=_digest("a-different-old-head"),
    )
    result = verify_log_consistency(proof, operator_public_key_pem=pem)
    assert result.status == STATUS_LOG_CHAIN_BROKEN


def test_consistency_malformed_ranges_refuse():
    private, pem = _signer()
    entries = _build_log(private)
    proof = _consistency_proof(private, entries, from_size=1)
    same = {**proof, "to_size": 1}
    assert verify_log_consistency(same, operator_public_key_pem=pem).status == STATUS_LOG_MALFORMED
    backwards = {**proof, "from_size": 3, "to_size": 1}
    assert (
        verify_log_consistency(backwards, operator_public_key_pem=pem).status
        == STATUS_LOG_MALFORMED
    )


